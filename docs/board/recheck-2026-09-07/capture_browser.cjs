
const {chromium}=require(process.env.CXPE_PLAYWRIGHT);
const fs=require('fs');
const path=require('path');
const base='http://127.0.0.1:8099';
const out=path.resolve('docs/board/recheck-2026-09-07/screens');
fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1600,height:1000}});
 const errors=[];const rows=[];
 page.on('pageerror',error=>errors.push(error.message));
 try {
  for(const [name,expected] of [['pass','PASS'],['fail_start','FAIL'],['fail_dropout','HOLD']]){
   let session;const end=Date.now()+600000;
   while(Date.now()<end){
    const data=await (await fetch(base+'/api/v1/sessions')).json();
    session=data.sessions.find(s=>s.case===name && s.summary.status==='finished');
    if(session)break;
    await new Promise(r=>setTimeout(r,3000));
   }
   if(!session)throw Error('No finished NPU trial: '+name);
   await page.goto(base+'/?session='+session.id);
   await page.waitForFunction(expected=>S.overall===expected && !S.busy,expected,{timeout:30000});
   if(!await page.locator('#btn-run').isDisabled() || !await page.locator('#btn-approve').isDisabled())throw Error('Finished trial is editable');
   const report=await page.locator('#report').textContent();
   const source=await page.locator('#report-meta').textContent();
   if(!report.includes('종합 판정: '+expected))throw Error('Wrong report result');
   if(!source.includes('geniex-18181'))throw Error('Report was not generated by the board model');
   await page.screenshot({path:out+'/'+name+'.png',fullPage:true});
   if(name==='pass'){
    await page.locator('#s-report > summary').click();
    await page.screenshot({path:out+'/pass-report.png',fullPage:true});
   }
   rows.push({case:name,session:session.id,overall:expected,historyReadOnly:true,reportSource:source});
   console.log('NPU UI verified '+name);
  }
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify({rows,errors},null,2));
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
